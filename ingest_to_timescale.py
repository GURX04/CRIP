def print_verification_summary(conn) -> None:
    """Run a set of SQL queries and print their results as a summary table."""
    queries = [
        (
            "aws_cur_records row count",
            "SELECT COUNT(*) FROM aws_cur_records;",
        ),
        (
            "aws_cur_records distinct services",
            "SELECT COUNT(DISTINCT product_code) FROM aws_cur_records;",
        ),
        (
            "aws_cur_records total cost (USD)",
            "SELECT ROUND(SUM(unblended_cost)::NUMERIC, 6) FROM aws_cur_records;",
        ),
        (
            "aws_cur_records time range",
            "SELECT MIN(usage_start)::TEXT || '  to  ' || MAX(usage_end)::TEXT"
            " FROM aws_cur_records;",
        ),
        (
            "system_telemetry row count",
            "SELECT COUNT(*) FROM system_telemetry;",
        ),
        (
            "system_telemetry distinct metrics",
            "SELECT COUNT(DISTINCT metric_name) FROM system_telemetry;",
        ),
        (
            "hypertable chunks (aws_cur_records)",
            "SELECT COUNT(*) FROM timescaledb_information.chunks"
            " WHERE hypertable_name = 'aws_cur_records';",
        ),
        (
            "hypertable chunks (system_telemetry)",
            "SELECT COUNT(*) FROM timescaledb_information.chunks"
            " WHERE hypertable_name = 'system_telemetry';",
        ),
    ]

    print()
    print("=" * 60)
    print("  POST-INGESTION VERIFICATION SUMMARY")
    print("=" * 60)
    with conn.cursor() as cur:
        for label, sql in queries:
            try:
                cur.execute(sql)
                result = cur.fetchone()[0]
                print(f"  {label:<42}  {result}")
            except Exception as exc:
                print(f"  {label:<42}  ERROR: {exc}")
    print("=" * 60)
    print()


