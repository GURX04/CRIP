def get_connection(host: str, port: int, dbname: str, user: str, password: str):
    """Return a psycopg2 connection with autocommit OFF."""
    log.info("Connecting to TimescaleDB at %s:%d/%s …", host, port, dbname)
    conn = psycopg2.connect(
        host=host,
        port=port,
        dbname=dbname,
        user=user,
        password=password,
        connect_timeout=10,
        application_name="crip-ingest",
    )
    conn.autocommit = False
    log.info("Connected.")
    return conn


def wait_for_db(host: str, port: int, dbname: str, user: str, password: str,
                retries: int = 15, delay: float = 3.0):
    """Retry the connection until TimescaleDB is ready (container startup)."""
    for attempt in range(1, retries + 1):
        try:
            conn = get_connection(host, port, dbname, user, password)
            conn.close()
            return
        except psycopg2.OperationalError as exc:
            log.warning("DB not ready (attempt %d/%d): %s", attempt, retries, exc)
            if attempt == retries:
                log.error("Could not connect to TimescaleDB after %d attempts.", retries)
                sys.exit(1)
            time.sleep(delay)


