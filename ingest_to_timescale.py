# Map CUR CSV column names → Python dict keys used in INSERT
_CUR_COLUMN_MAP: Dict[str, str] = {
    "lineItem/UsageStartDate":    "usage_start",
    "lineItem/UsageEndDate":      "usage_end",
    "identity/LineItemId":        "line_item_id",
    "bill/InvoiceId":             "invoice_id",
    "bill/BillType":              "bill_type",
    "bill/PayerAccountId":        "payer_account_id",
    "lineItem/ProductCode":       "product_code",
    "lineItem/UsageType":         "usage_type",
    "lineItem/Operation":         "operation",
    "lineItem/AvailabilityZone":  "availability_zone",
    "lineItem/ResourceId":        "resource_id",
    "lineItem/UsageAmount":       "usage_amount",
    "lineItem/UnblendedRate":     "unblended_rate",
    "lineItem/UnblendedCost":     "unblended_cost",
    "lineItem/BlendedRate":       "blended_rate",
    "lineItem/BlendedCost":       "blended_cost",
    "lineItem/CurrencyCode":      "currency_code",
    "product/ProductName":        "product_name",
    "product/servicecode":        "service_code",
    "product/region":             "region",
    "resourceTags/user:Project":      "tag_project",
    "resourceTags/user:Environment":  "tag_environment",
    "resourceTags/user:Team":         "tag_team",
}

_CUR_INSERT_SQL = """
INSERT INTO aws_cur_records (
    usage_start, usage_end,
    line_item_id, invoice_id, bill_type, payer_account_id,
    product_code, usage_type, operation, availability_zone, resource_id,
    usage_amount, unblended_rate, unblended_cost,
    blended_rate, blended_cost, currency_code,
    product_name, service_code, region,
    tag_project, tag_environment, tag_team
) VALUES %s
ON CONFLICT (usage_start, line_item_id) DO NOTHING;
"""

# Template string for execute_values
_CUR_ROW_TEMPLATE = """(
    %(usage_start)s, %(usage_end)s,
    %(line_item_id)s, %(invoice_id)s, %(bill_type)s, %(payer_account_id)s,
    %(product_code)s, %(usage_type)s, %(operation)s, %(availability_zone)s, %(resource_id)s,
    %(usage_amount)s, %(unblended_rate)s, %(unblended_cost)s,
    %(blended_rate)s, %(blended_cost)s, %(currency_code)s,
    %(product_name)s, %(service_code)s, %(region)s,
    %(tag_project)s, %(tag_environment)s, %(tag_team)s
)"""


def _parse_float(val: str) -> Optional[float]:
    """Safely convert a CSV string to float, returning None on empty/invalid."""
    if val is None or val.strip() == "":
        return None
    try:
        return float(val)
    except ValueError:
        return None


def _parse_ts(val: str) -> Optional[datetime]:
    """Parse ISO-8601 UTC timestamp string to an aware datetime."""
    if not val:
        return None
    # Handles both 'Z' suffix and '+00:00'
    val = val.replace("Z", "+00:00")
    try:
        return datetime.fromisoformat(val)
    except ValueError:
        return None


def _map_cur_row(raw: Dict[str, str]) -> Dict[str, Any]:
    """Convert a raw CSV dict row into a typed dict for psycopg2."""
    mapped: Dict[str, Any] = {}

    for csv_col, db_col in _CUR_COLUMN_MAP.items():
        raw_val = raw.get(csv_col, "")

        if db_col in ("usage_start", "usage_end"):
            mapped[db_col] = _parse_ts(raw_val)
        elif db_col in (
            "usage_amount", "unblended_rate", "unblended_cost",
            "blended_rate", "blended_cost",
        ):
            mapped[db_col] = _parse_float(raw_val)
        else:
            mapped[db_col] = raw_val if raw_val else None

    return mapped


def ingest_cur(conn, csv_path: Path, batch_size: int) -> Tuple[int, int]:
    """
    Bulk-insert CUR CSV rows into aws_cur_records.

    Returns (rows_processed, rows_inserted).
    """
    log.info("Reading CUR file: %s", csv_path)

    rows_processed = 0
    rows_inserted  = 0
    skipped        = 0
    batch: List[Dict[str, Any]] = []

    with open(csv_path, encoding="utf-8", newline="") as fh:
        reader = csv.DictReader(fh)
        total_estimate = None  # will count as we go

        with conn.cursor() as cur:
            for raw_row in reader:
                rows_processed += 1

                mapped = _map_cur_row(raw_row)

                # Skip rows with missing mandatory fields
                if not mapped.get("usage_start") or not mapped.get("line_item_id"):
                    skipped += 1
                    continue

                batch.append(mapped)

                if len(batch) >= batch_size:
                    psycopg2.extras.execute_values(
                        cur, _CUR_INSERT_SQL, batch,
                        template=_CUR_ROW_TEMPLATE,
                        page_size=batch_size,
                    )
                    rows_inserted += cur.rowcount
                    conn.commit()
                    log.info(
                        "  CUR batch committed: %d rows processed so far …",
                        rows_processed,
                    )
                    batch.clear()

            # Final partial batch
            if batch:
                psycopg2.extras.execute_values(
                    cur, _CUR_INSERT_SQL, batch,
                    template=_CUR_ROW_TEMPLATE,
                    page_size=batch_size,
                )
                rows_inserted += cur.rowcount
                conn.commit()

    log.info(
        "CUR ingestion complete: %d rows processed, %d inserted, %d skipped.",
        rows_processed, rows_inserted, skipped,
    )
    return rows_processed, rows_inserted


