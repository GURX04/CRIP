"""
ingest_to_timescale.py
======================
CRIP Phase 2 — Ingestion Pipeline

Responsibilities
----------------
1. CUR Ingestion
   Reads  : reports/synthetic_cur.csv  (generated by generate_cur.py)
   Writes : aws_cur_records hypertable in TimescaleDB
   Method : psycopg2 execute_values() bulk insert with ON CONFLICT DO NOTHING
            for idempotent re-runs.

2. Telemetry Ingestion
   Reads  : Prometheus HTTP API (instant query)
   Writes : system_telemetry hypertable in TimescaleDB
   Metrics: cpu_usage_rate, memory_usage_bytes, memory_usage_pct,
            http_requests_rate, http_error_rate, active_requests,
            ingest_bytes_rate

Usage
-----
  # Prerequisites: pip install psycopg2-binary requests
  python ingest_to_timescale.py

  # Override defaults with env vars or CLI flags:
  python ingest_to_timescale.py \\
      --cur-file reports/synthetic_cur.csv \\
      --db-host  localhost  --db-port 5432 \\
      --db-name  crip       --db-user crip_user  --db-pass crip_secret \\
      --prom-url http://localhost:9090 \\
      --batch-size 500
"""

