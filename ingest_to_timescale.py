_TELEMETRY_INSERT_SQL = """
INSERT INTO system_telemetry (ts, metric_name, job, instance, service, labels, value)
VALUES %s
ON CONFLICT DO NOTHING;
"""

_TELEMETRY_ROW_TEMPLATE = """(
    %(ts)s, %(metric_name)s, %(job)s, %(instance)s, %(service)s,
    %(labels)s, %(value)s
)"""


# Prometheus instant-query expressions to collect
# Each entry: (human_label, promql_expression)
_PROM_QUERIES: List[Tuple[str, str]] = [
    (
        "cpu_usage_rate_1m",
        # Average CPU usage rate across all modes for all CPUs
        '1 - avg(rate(node_cpu_seconds_total{mode="idle"}[1m]))',
    ),
    (
        "memory_used_bytes",
        # Memory actually used = total - (free + buffers + cached)
        "node_memory_MemTotal_bytes - node_memory_MemAvailable_bytes",
    ),
    (
        "memory_usage_pct",
        # As a fraction (0–1)
        "(node_memory_MemTotal_bytes - node_memory_MemAvailable_bytes)"
        " / node_memory_MemTotal_bytes",
    ),
    (
        "http_requests_rate_1m",
        # CRIP target app request throughput
        'rate(crip_http_requests_total[1m])',
    ),
    (
        "http_error_rate_1m",
        # CRIP target app error throughput
        'rate(crip_http_errors_total[1m])',
    ),
    (
        "active_requests",
        "crip_active_requests",
    ),
    (
        "ingest_bytes_rate_1m",
        "rate(crip_ingest_bytes_total[1m])",
    ),
    (
        "app_uptime_seconds",
        "crip_app_uptime_seconds",
    ),
]


def _query_prometheus_instant(
    prom_url: str, expr: str, timeout: float = 10.0
) -> List[Dict[str, Any]]:
    """
    Execute a Prometheus instant query and return a list of result dicts.
    Each dict has: metric (labels), value (float), ts (datetime).
    Returns an empty list on any error (Prometheus may not be running).
    """
    url = f"{prom_url.rstrip('/')}/api/v1/query"
    try:
        resp = requests.get(
            url,
            params={"query": expr, "time": time.time()},
            timeout=timeout,
        )
        resp.raise_for_status()
        data = resp.json()
    except requests.RequestException as exc:
        log.warning("Prometheus query failed (%s): %s", expr[:60], exc)
        return []

    if data.get("status") != "success":
        log.warning("Prometheus returned non-success for '%s': %s", expr, data)
        return []

    results = []
    for result in data["data"]["result"]:
        metric_labels = result.get("metric", {})
        ts_unix, val_str = result["value"]
        try:
            val = float(val_str)
        except (ValueError, TypeError):
            continue

        results.append({
            "metric_labels": metric_labels,
            "ts":  datetime.fromtimestamp(float(ts_unix), tz=timezone.utc),
            "value": val,
        })

    return results


def _build_telemetry_rows(
    label: str,
    prom_results: List[Dict[str, Any]],
) -> List[Dict[str, Any]]:
    """Convert Prometheus instant-query results into system_telemetry row dicts."""
    rows = []
    for r in prom_results:
        ml = r["metric_labels"]
        # Serialize all Prometheus labels as JSONB
        import json
        rows.append({
            "ts":          r["ts"],
            "metric_name": label,
            "job":         ml.get("job"),
            "instance":    ml.get("instance"),
            "service":     ml.get("service"),
            "labels":      json.dumps(ml) if ml else None,
            "value":       r["value"],
        })
    return rows


def ingest_telemetry(conn, prom_url: str, batch_size: int) -> Tuple[int, int]:
    """
    Query Prometheus for each metric in _PROM_QUERIES and insert into
    system_telemetry. Returns (queries_run, rows_inserted).
    """
    log.info("Querying Prometheus at %s …", prom_url)

    queries_run   = 0
    rows_inserted = 0
    all_rows: List[Dict[str, Any]] = []

    for label, expr in _PROM_QUERIES:
        log.info("  Querying: %s  [%s]", label, expr[:70])
        prom_results = _query_prometheus_instant(prom_url, expr)
        queries_run += 1

        if not prom_results:
            log.warning("  No data returned for metric '%s' — is Prometheus running?", label)
            continue

        rows = _build_telemetry_rows(label, prom_results)
        all_rows.extend(rows)
        log.info("  Got %d sample(s) for '%s'.", len(rows), label)

    if not all_rows:
        log.warning("No telemetry rows to insert. Skipping.")
        return queries_run, 0

    # Bulk-insert in batches
    with conn.cursor() as cur:
        for i in range(0, len(all_rows), batch_size):
            chunk = all_rows[i : i + batch_size]
            psycopg2.extras.execute_values(
                cur, _TELEMETRY_INSERT_SQL, chunk,
                template=_TELEMETRY_ROW_TEMPLATE,
                page_size=batch_size,
            )
            rows_inserted += cur.rowcount
        conn.commit()

    log.info(
        "Telemetry ingestion complete: %d queries, %d rows inserted.",
        queries_run, rows_inserted,
    )
    return queries_run, rows_inserted


