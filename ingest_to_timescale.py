def _parse_args() -> argparse.Namespace:
    p = argparse.ArgumentParser(
        description="CRIP Phase 2 — Ingest CUR + Prometheus telemetry into TimescaleDB.",
        formatter_class=argparse.ArgumentDefaultsHelpFormatter,
    )

    # CUR
    p.add_argument("--cur-file",   default="reports/synthetic_cur.csv",
                   help="Path to the synthetic CUR CSV file.")
    p.add_argument("--skip-cur",   action="store_true",
                   help="Skip CUR ingestion.")

    # Prometheus
    p.add_argument("--prom-url",   default=os.getenv("PROM_URL", "http://localhost:9090"),
                   help="Prometheus base URL.")
    p.add_argument("--skip-prom",  action="store_true",
                   help="Skip Prometheus telemetry ingestion.")

    # Database
    p.add_argument("--db-host",    default=os.getenv("DB_HOST",   "localhost"))
    p.add_argument("--db-port",    type=int,
                   default=int(os.getenv("DB_PORT",   "5432")))
    p.add_argument("--db-name",    default=os.getenv("DB_NAME",   "crip"))
    p.add_argument("--db-user",    default=os.getenv("DB_USER",   "crip_user"))
    p.add_argument("--db-pass",    default=os.getenv("DB_PASS",   "crip_secret"))

    # Tuning
    p.add_argument("--batch-size", type=int, default=500,
                   help="Rows per INSERT batch.")
    p.add_argument("--db-retries", type=int, default=15,
                   help="Connection retries while waiting for DB startup.")

    return p.parse_args()


def main() -> None:
    args = _parse_args()

    # --- Wait for DB ---
    wait_for_db(
        args.db_host, args.db_port,
        args.db_name, args.db_user, args.db_pass,
        retries=args.db_retries,
    )

    conn = get_connection(
        args.db_host, args.db_port,
        args.db_name, args.db_user, args.db_pass,
    )

    try:
        # --- CUR Ingestion ---
        if not args.skip_cur:
            cur_path = Path(args.cur_file)
            if not cur_path.exists():
                log.error(
                    "CUR file not found: %s\n"
                    "Run generate_cur.py first, or pass --skip-cur.",
                    cur_path.resolve(),
                )
                sys.exit(1)
            ingest_cur(conn, cur_path, args.batch_size)
        else:
            log.info("Skipping CUR ingestion (--skip-cur).")

        # --- Telemetry Ingestion ---
        if not args.skip_prom:
            ingest_telemetry(conn, args.prom_url, args.batch_size)
        else:
            log.info("Skipping Prometheus ingestion (--skip-prom).")

        # --- Verification ---
        print_verification_summary(conn)

    except KeyboardInterrupt:
        log.info("Interrupted by user.")
        conn.rollback()
    except Exception as exc:
        log.exception("Unexpected error during ingestion: %s", exc)
        conn.rollback()
        sys.exit(1)
    finally:
        conn.close()
        log.info("Database connection closed.")


if __name__ == "__main__":
    main()
